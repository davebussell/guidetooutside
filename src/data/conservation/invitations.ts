/**
 * Open invitations: the specific, current things an organisation in the
 * library is asking people to do — a count, a cleanup, a planting day, a
 * season-long survey, a weekly walk. These are what the site features: a
 * reader sees "Project FeederWatch opens 1 November — count your feeder birds
 * all winter" with a photo and a button, not just an organisation's name.
 *
 * Every invitation belongs to a library organisation (`org` is its slug),
 * links to the organisation's own sign-up or details page (fetched this
 * session, 200), and carries its dates as the organisation states them. An
 * invitation with dates disappears by itself once it has ended; `ongoing`
 * ones (an app-based survey, a monthly sampling programme) stay until a
 * re-check says otherwise. `verified` is the day the dates and link were
 * last checked against `sources`.
 *
 * Photos are ours to use: CC0 / CC BY / CC BY-SA images of the subject (the
 * bird, the river, the plant), stored in `public/conservation/` as webp with
 * the credit shown under them — never an organisation's own photographs or
 * logos, which we have no licence for.
 */
import type { ServiceArea, Topic } from "./types";

export type When =
  /** A fixed window, ISO dates inclusive ("2026-12-14" … "2027-01-05"). */
  | { kind: "dates"; start: string; end: string; note?: string }
  /** The same months every year, in the reader's hemisphere as the organisation runs it (1 = January). */
  | { kind: "months"; months: number[]; note?: string }
  /** A standing weekly or monthly fixture ("Every Wednesday morning", "First Saturday of the month"). */
  | { kind: "recurring"; rule: string; months?: number[] }
  /** Open all year (an app, an atlas, a reporting line). */
  | { kind: "ongoing"; note?: string };

export type Effort = "minutes" | "an hour" | "an afternoon" | "a day" | "all season";

export type Photo = {
  /** Path under /public, e.g. "/conservation/feederwatch-chickadee.webp" (≤ 1600 px wide, webp). */
  src: string;
  alt: string;
  author: string;
  license: string;
  licenseUrl: string;
  /** The image's page (Wikimedia Commons file page or iNaturalist observation). */
  source: string;
};

export type Invitation = {
  /** Unique, kebab-case, e.g. "project-feederwatch-2026-27". */
  slug: string;
  /** The library organisation running it (must exist in ORGANISATIONS). */
  org: string;
  /** Other library organisations that co-run it ("Cornell Lab" with "Birds Canada"). */
  partners?: string[];
  /** The invitation as a reader would say it: "Count the birds at your feeder this winter". */
  title: string;
  /** Its own name when it has one: "Project FeederWatch", "Christmas Bird Count". */
  name?: string;
  /** One or two plain sentences: what you actually do, and what it is for. */
  summary: string;
  kind: "count" | "survey" | "cleanup" | "planting" | "walk" | "event" | "programme" | "challenge" | "report";
  effort: Effort;
  /** Fine for children with an adult. */
  family: boolean;
  /** Needs nothing but a phone or a window (no travel, no kit). */
  fromHome?: boolean;
  /** Free to take part (membership or a fee → false, and say so in `cost`). */
  free: boolean;
  cost?: string;
  when: When;
  /** Where it applies; omit for wherever the organisation's own areas reach. */
  areas?: ServiceArea[];
  topics: Topic[];
  /** The organisation's own page to sign up or read the details. */
  url: string;
  /** The button's words: "Sign up for FeederWatch", "Find a count near you", "Book a place". */
  cta: string;
  photo?: Photo;
  verified: string;
  sources: string[];
};

